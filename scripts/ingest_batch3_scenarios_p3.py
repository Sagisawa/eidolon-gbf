def compute_vector(text: str, dim: int = 1536) -> bytes:
    vec = [0.0] * dim
    for ch in text:
        h = int(hashlib.md5(ch.encode("utf-8")).hexdigest()[:8], 16) % dim
        vec[h] += 1.0
    for i in range(len(text) - 1):
        bi = text[i:i+2]
        h = int(hashlib.md5(bi.encode("utf-8")).hexdigest()[:8], 16) % dim
        vec[h] += 2.0
    for i in range(len(text) - 2):
        tri = text[i:i+3]
        h = int(hashlib.md5(tri.encode("utf-8")).hexdigest()[:8], 16) % dim
        vec[h] += 3.0
    norm = math.sqrt(sum(x * x for x in vec)) or 1.0
    vec = [x / norm for x in vec]
    return struct.pack(f"<{dim}f", *vec)


def ingest_episode(
    conn: sqlite3.Connection,
    title: str,
    category: str,
    cast: list[str],
    lines: list[tuple[str, str, str]],
):
    cur = conn.cursor()
    ep_id = f"ep_b3_{uuid.uuid4().hex[:8]}"
    now_iso = datetime.now().isoformat()

    cur.execute(
        "INSERT INTO episodes (id, category, source, title, imported_from, imported_at) VALUES (?, ?, ?, ?, ?, ?)",
        (ep_id, category, "official_gbf_lore", title, "batch3_scenarios_p3", now_iso),
    )
    for char_id in cast:
        cur.execute(
            "INSERT OR IGNORE INTO episode_cast (episode_id, character_id) VALUES (?, ?)",
            (ep_id, char_id),
        )
    for seq, (spk, ja, zh) in enumerate(lines, start=1):
        cur.execute(
            "INSERT INTO episode_lines (episode_id, seq, speaker, ja, zh) VALUES (?, ?, ?, ?, ?)",
            (ep_id, seq, spk, ja, zh),
        )
    full_text = " ".join(f"{spk} {ja} {zh}" for spk, ja, zh in lines)
    for char_id in cast:
        cur.execute(
            "INSERT INTO episode_fts (episode_id, character_id, title, text) VALUES (?, ?, ?, ?)",
            (ep_id, char_id, title, full_text),
        )
    passage_text = f"{title}\n" + "\n".join(f"{spk}：{ja}（{zh}）" for spk, ja, zh in lines)
    vec_blob = compute_vector(passage_text)
    cur.execute(
        "INSERT OR REPLACE INTO episode_passages (episode_id, seq, text, model, embedding) VALUES (?, 0, ?, 'builtin-bm25-vector', ?)",
        (ep_id, passage_text, vec_blob),
    )


def make_seasonal_episodes(char_id: str, char_name: str, dancho_term: str, specific_seasons: dict[str, list[tuple[str, str]]]):
    episodes = []
    season_tags = [
        ("新年", "newyear"),
        ("情人节", "valentine"),
        ("白色情人节", "whiteday"),
        ("万圣节", "halloween"),
        ("圣诞节", "christmas"),
        ("生日祝词", "birthday"),
    ]
    for name, tag in season_tags:
        lines_list = specific_seasons.get(tag, [])
        for year in range(1, 4):
            idx = year - 1
            if idx < len(lines_list):
                ja, zh = lines_list[idx]
            else:
                ja, zh = (f"{dancho_term}、{name}おめでとう！", f"{dancho_term}，{name}快乐！")
            ep_title = f"{char_name} {name}特别剧情 {year}年目 [season:{tag}]"
            episodes.append((ep_title, "特别剧情", [char_id], [(char_name, ja, zh)]))
    return episodes


