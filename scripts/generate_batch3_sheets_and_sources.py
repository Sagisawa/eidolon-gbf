def main():
    sheets_dir = Path("characters/sheets")
    facts_dir = Path("characters/facts")
    sheets_dir.mkdir(parents=True, exist_ok=True)
    facts_dir.mkdir(parents=True, exist_ok=True)

    # 1. Sheets
    for cid, content in SHEETS.items():
        out = sheets_dir / f"{cid}.md"
        out.write_text(content.strip() + "\n", encoding="utf-8")
        print(f"Generated sheet: {out} ({len(content.splitlines())} lines)")

    # 2. Sources
    for cid, data in SOURCES_DATA.items():
        out = facts_dir / f"{cid}.sources.md"
        src_text = SOURCES_TEMPLATE.format(
            name=data["name"],
            events=data["events"],
            fates=data["fates"],
            gifts=data["gifts"],
        )
        out.write_text(src_text.strip() + "\n", encoding="utf-8")
        print(f"Generated sources: {out} ({len(src_text.splitlines())} lines)")

    print("\nAll 13 character sheets and sources successfully generated!")


if __name__ == "__main__":
    main()
