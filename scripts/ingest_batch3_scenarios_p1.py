def main():
    conn = sqlite3.connect(DB_PATH)
    total = 0

    # Clean previous partial run
    cur = conn.cursor()
    cur.execute("SELECT id FROM episodes WHERE imported_from = 'batch3_scenarios_p1'")
    old_ids = [r[0] for r in cur.fetchall()]
    if old_ids:
        cur.executemany("DELETE FROM episode_cast WHERE episode_id = ?", [(i,) for i in old_ids])
        cur.executemany("DELETE FROM episode_lines WHERE episode_id = ?", [(i,) for i in old_ids])
        cur.executemany("DELETE FROM episode_fts WHERE episode_id = ?", [(i,) for i in old_ids])
        cur.executemany("DELETE FROM episode_passages WHERE episode_id = ?", [(i,) for i in old_ids])
        cur.executemany("DELETE FROM episodes WHERE id = ?", [(i,) for i in old_ids])
        conn.commit()

    # Ingest Azusa
    print("Ingesting Azusa...")
    azusa_eps = [(t, c, ["azusa"], l) for t, c, l in AZUSA_EPISODES]
    for title, cat, cast, lines in azusa_eps:
        ingest_episode(conn, title, cat, cast, lines)
        total += 1

    # Ingest Orchid
    print("Ingesting Orchid...")
    orchid_eps = (
        [(t, c, ["orchid"], l) for t, c, l in ORCHID_FATES]
        + make_seasonal_episodes("orchid", "オーキス", "団長", ORCHID_SEASONS)
        + [(t, c, ["orchid"], l) for t, c, l in ORCHID_DAILIES]
    )
    for title, cat, cast, lines in orchid_eps:
        ingest_episode(conn, title, cat, cast, lines)
        total += 1

    # Ingest Zeta
    print("Ingesting Zeta...")
    zeta_eps = (
        [(t, c, ["zeta"], l) for t, c, l in ZETA_FATES]
        + make_seasonal_episodes("zeta", "ゼタ", "団長", ZETA_SEASONS)
        + [(t, c, ["zeta"], l) for t, c, l in ZETA_DAILIES]
    )
    for title, cat, cast, lines in zeta_eps:
        ingest_episode(conn, title, cat, cast, lines)
        total += 1

    # Ingest Meg
    print("Ingesting Meg...")
    meg_eps = (
        [(t, c, ["meg"], l) for t, c, l in MEG_FATES]
        + make_seasonal_episodes("meg", "メグ", "団長さん", MEG_SEASONS)
        + [(t, c, ["meg"], l) for t, c, l in MEG_DAILIES]
    )
    for title, cat, cast, lines in meg_eps:
        ingest_episode(conn, title, cat, cast, lines)
        total += 1

    conn.commit()
    conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    conn.close()
    print(f"Successfully ingested {total} episodes for Azusa, Orchid, Zeta, Meg into {DB_PATH}!")


if __name__ == "__main__":
    main()
