def main():
    print("=== Writing Sheets, Facts, and Scenario CSVs for 5 Divine Generals ===")

    # 1. Sheets
    sheets_dir = ROOT / "characters" / "sheets"
    sheets_dir.mkdir(parents=True, exist_ok=True)
    for cid, text in SHEETS.items():
        p = sheets_dir / f"{cid}.md"
        p.write_text(text, encoding="utf-8")
        print(f"  -> Generated sheet: {p.name}")

    # 2. Facts and Sources
    facts_dir = ROOT / "characters" / "facts"
    facts_dir.mkdir(parents=True, exist_ok=True)
    facts_meta = {
        "anila": ("アニラ", "未（羊）", "悠木碧", "火", "槍・格闘", "金剛三叉戟、羊神宮、太陽の炎"),
        "andira": ("アンチラ", "申（猴）", "内田彩", "风", "杖・格闘", "如意棒、申神宮、疾風の霊力"),
        "mahira": ("マキラ", "酉（鸡）", "門脇舞以", "土", "楽器・格闘", "からくり鳥クック、酉神宮、大地の響き"),
        "vajra": ("ヴァジラ", "戌（狗）", "芹澤優", "水", "刀・格闘", "神犬ガルジャナ、戌神宮、水天の抜刀術"),
        "kumbhira": ("クビラ", "亥（猪）", "堀江由衣", "光", "槍・斧", "神使ポポ、亥神宮、破邪の金光"),
    }
    for cid, (cname, zname, cv, ele, wep, desc) in facts_meta.items():
        f_text, s_text = get_facts_content(cid, cname, zname, cv, ele, wep, desc)
        (facts_dir / f"{cid}.md").write_text(f_text, encoding="utf-8")
        (facts_dir / f"{cid}.sources.md").write_text(s_text, encoding="utf-8")
        print(f"  -> Generated facts & sources: {cid}")

    # 3. Scenarios
    corpus_base = ROOT / "corpus" / "gbf"
    dh_map = {
        "anila": "団長殿",
        "andira": "団長",
        "mahira": "団長殿",
        "vajra": "団長殿",
        "kumbhira": "団長さん",
    }
    for cid, (cname, _, _, _, _, _) in facts_meta.items():
        c_dir = corpus_base / cid
        c_dir.mkdir(parents=True, exist_ok=True)
        scenarios = get_scenarios(cid, cname, dh_map[cid])
        for filename, lines in scenarios:
            csv_path = c_dir / filename
            with csv_path.open("w", encoding="utf-8-sig", newline="") as f:
                writer = csv.writer(f)
                writer.writerow(["id", "name", "text", "trans"])
                for idx, (spk, ja, zh) in enumerate(lines, 1):
                    writer.writerow([str(idx), spk, ja, zh])
                writer.writerow(["info", "", "", csv_path.stem])
        print(f"  -> Generated {len(scenarios)} CSV scenarios for {cid} under corpus/gbf/{cid}")

    print("All Phase 1 text & scenario assets generated successfully!")


if __name__ == "__main__":
    main()
