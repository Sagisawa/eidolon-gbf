def main():
    written = 0
    for name, dialogs in SCENARIOS.items():
        csv_path = CORPUS_DIR / f"{name}.csv"
        with open(csv_path, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["id", "name", "text", "trans"])
            for idx, (speaker, ja, zh) in enumerate(dialogs, start=1):
                writer.writerow([idx, speaker, ja, zh])
            writer.writerow(["info", "", "", name])
        written += 1
    print(f"Successfully generated {written} scenario CSVs in {CORPUS_DIR}!")

if __name__ == "__main__":
    main()
