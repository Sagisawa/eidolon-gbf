def write_csv(path: Path, lines: list[tuple[str, str, str]]):
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["id", "name", "text", "trans"])
        for idx, (spk, ja, zh) in enumerate(lines, 1):
            writer.writerow([str(idx), spk, ja, zh])
        stem = path.stem
        writer.writerow(["info", "", "", stem])


def main():
    print(f"Scaffolding {len(EPISODES)} scenario CSVs for Nier under {BASE_DIR}...")
    for filename, lines in EPISODES:
        target = BASE_DIR / filename
        write_csv(target, lines)
        print(f"  -> Generated {filename} ({len(lines)} lines)")
    print("Done!")


if __name__ == "__main__":
    main()
