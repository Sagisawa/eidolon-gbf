def build_address_markdown(addresses: list[tuple[str, str]]) -> str:
    lines = ["## 对他人的称呼"]
    for role, call in addresses:
        lines.append(f"- **{role}**：{call}")
    return "\n".join(lines)


def patch_sheet(char_id: str, addresses: list[tuple[str, str]]):
    sheet_path = Path(f"characters/sheets/{char_id}.md")
    if not sheet_path.exists():
        print(f"Warning: Sheet {sheet_path} does not exist!")
        return

    content = sheet_path.read_text(encoding="utf-8")
    if "对他人的称呼" in content:
        print(f"Skipping {char_id}: already has address section.")
        return

    address_md = build_address_markdown(addresses)

    # Strategy: find where to insert.
    # If there's '## 三阶段情绪行为状态机', insert before it.
    # If there's '## 二、三层行为状态机', insert before it.
    # If there's '## 关系阶段', insert before it.
    # If there's '## 硬性规则', insert before it.
    inserted = False
    for target in [
        "## 三阶段情绪行为状态机",
        "## 二、三层行为状态机",
        "## 关系阶段（三档羁绊状态机）",
        "## 典型对话示例",
        "## 核心心境与团长的关系",
        "## 三、三层意识与行为状态机",
        "## 硬性规则",
    ]:
        if target in content:
            content = content.replace(target, f"{address_md}\n\n{target}", 1)
            inserted = True
            break

    if not inserted:
        content = content.rstrip() + f"\n\n{address_md}\n"

    sheet_path.write_text(content, encoding="utf-8")
    print(f"Successfully patched {char_id}")


def main():
    print(f"Patching {len(ADDRESS_MAP)} character sheets...")
    for char_id, addresses in ADDRESS_MAP.items():
        patch_sheet(char_id, addresses)
    print("All sheets patched successfully!")


if __name__ == "__main__":
    main()
