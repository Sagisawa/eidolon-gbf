def main():
    conn = sqlite3.connect(DB_PATH)
    print(f"Connected to {DB_PATH}")

    total_inserted = 0
    for title, category, cast, lines in TRILOGY_EPISODES:
        print(f"Ingesting: {title} (Cast: {', '.join(cast)})")
        ingest_episode(conn, title, category, cast, lines)
        total_inserted += 1

    conn.commit()
    conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    conn.close()
    print(f"\nAll {total_inserted} episodes of the Trilogy successfully ingested into {DB_PATH}!")


if __name__ == "__main__":
    main()
